/**
 * プロトタイプの画面説明パネル（KitScreenDescription）に出す、利用者向けの説明。
 *
 * screenDescriptions.ts は開発者向け（ガイド › 画面説明・画面設計の右パネルに写す元）なので、こちらは
 * 実際にシステムを使う人（工場・本社で帳票を準備する管理者）が読む言葉で書く。
 * 画面の作りの話（空欄で出す・トースト・URL など）は書かず、「何のための画面か・どう操作するか・気をつけること」だけにする。
 *
 * 操作は「やりたいこと」（tasks の title）ごとに、上から順に行う手順（steps）で書く。パネルでは 1. 2. 3. の番号付きで出る。
 * 1 つの手順に 1 つの操作。ボタンや欄の名前は画面に出ている文字どおり「」で書く。
 * キーは screenDescriptions.ts と同じ画面ファイルのパス。ここに無い画面は「準備中」と出す。
 */

/** やりたいこと 1 つぶんの操作手順 */
export type KitUserTask = {
  /** やりたいこと（例：「持ち場/ラインを追加する」） */
  title: string;
  /** 上から順に行う手順。パネルでは番号付きで出る */
  steps: string[];
};

/** ポップアップが出ている間の説明（見出しが whenHeading を含むポップアップが出ていたら、こちらに差し替わる） */
export type KitUserStateDescription = {
  whenHeading: string;
  /** 画面名に添える短い名前 */
  label: string;
  summary: string;
  tasks: KitUserTask[];
  note?: string;
};

export type KitUserDescription = {
  summary: string;
  tasks: KitUserTask[];
  note?: string;
  states?: KitUserStateDescription[];
};

